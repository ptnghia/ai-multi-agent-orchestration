import fs from 'node:fs';
import path from 'node:path';
import { run } from './exec.js';
import { listTaskIds, loadState, loadTask, readJson, taskDir } from './store.js';
import type { TaskResult } from './types.js';

/**
 * Repo-local project memory (<repo>/.context/), readable by every agent and
 * every Claude session regardless of where it was started. AIO owns the
 * generated block of ACTIVE.md and appends HISTORY.md, so nobody has to
 * remember to update them.
 */

const BEGIN = '<!-- aio:begin (generated by AIO; edits inside are overwritten) -->';
const END = '<!-- aio:end -->';
const HISTORY_MAX = 150;
const HISTORY_KEEP = 100;

const ACTIVE_TEMPLATE = `# ACTIVE — current state (keep under ~40 lines)

## Focus
- (what this wave is about; edit by hand)

## Open follow-ups
- (edit by hand)

${BEGIN}
${END}
`;

const contextDir = (repo: string) => path.join(repo, '.context');
const today = () => new Date().toISOString().slice(0, 10);

function lastResult(id: string): TaskResult | undefined {
  const file = path.join(taskDir(id), 'result.json');
  return fs.existsSync(file) ? readJson<TaskResult>(file) : undefined;
}

function generatedBlock(repo: string): string {
  const tasks = listTaskIds()
    .map((id) => ({ task: loadTask(id), state: loadState(id) }))
    .filter(({ task }) => path.resolve(task.repo) === path.resolve(repo));
  const open = tasks.filter(({ state }) => state.status !== 'approved');
  const done = tasks
    .filter(({ state }) => state.status === 'approved')
    .sort((a, b) => b.state.updated_at.localeCompare(a.state.updated_at))
    .slice(0, 5);

  const lines = ['## AIO tasks'];
  if (open.length) {
    lines.push('| Task | Agent | Status | Last result |', '|---|---|---|---|');
    for (const { task, state } of open) {
      const r = lastResult(task.id);
      const failed = r ? r.checks.filter((c) => !c.ok).map((c) => c.name).join('; ') : '';
      lines.push(`| ${task.id} | ${task.agent} | ${state.status} | ${r ? r.status : '-'}${failed ? ` (${failed.slice(0, 80)})` : ''} |`);
    }
  } else {
    lines.push('No open tasks.');
  }
  if (done.length) lines.push('', `Recently approved: ${done.map(({ task }) => task.id).join(', ')}`);
  lines.push('', 'Details: `aio status`, `aio show <id>`. History: .context/HISTORY.md (read with tail).');
  return lines.join('\n');
}

/** Rewrites only the generated block of ACTIVE.md, keeping hand-written sections. */
export function syncActive(repo: string): void {
  const file = path.join(contextDir(repo), 'ACTIVE.md');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  let text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ACTIVE_TEMPLATE;
  if (!text.includes(BEGIN) || !text.includes(END)) text = `${text.trimEnd()}\n\n${BEGIN}\n${END}\n`;
  const start = text.indexOf(BEGIN) + BEGIN.length;
  const end = text.indexOf(END);
  fs.writeFileSync(file, `${text.slice(0, start)}\n${generatedBlock(repo)}\n${text.slice(end)}`);
}

/** Appends one line to HISTORY.md and rotates old entries into history/<year>.md. */
export function appendHistory(repo: string, entry: string): void {
  const dir = contextDir(repo);
  const file = path.join(dir, 'HISTORY.md');
  fs.mkdirSync(dir, { recursive: true });
  if (!fs.existsSync(file)) fs.writeFileSync(file, '# HISTORY — append-only, newest last. Read with tail, never in full.\n\n');
  fs.appendFileSync(file, `[${today()}] ${entry.replace(/\s+/g, ' ').trim()}\n`);

  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const entries = lines.filter((l) => l.startsWith('['));
  if (entries.length <= HISTORY_MAX) return;
  const archive = entries.slice(0, entries.length - HISTORY_KEEP);
  const archiveFile = path.join(dir, 'history', `${new Date().getFullYear()}.md`);
  fs.mkdirSync(path.dirname(archiveFile), { recursive: true });
  fs.appendFileSync(archiveFile, archive.join('\n') + '\n');
  const header = lines.filter((l) => !l.startsWith('[') && l.trim()).join('\n');
  fs.writeFileSync(file, `${header}\n\n${entries.slice(-HISTORY_KEEP).join('\n')}\n`);
}

/** Records an event and refreshes ACTIVE.md. Never throws: context upkeep must not break a run. */
export function recordEvent(repo: string, entry: string): void {
  try {
    appendHistory(repo, entry);
    syncActive(repo);
  } catch (e) {
    console.error(`context update failed: ${(e as Error).message}`);
  }
}

/** Commits only .context/ so the shared memory travels with the repo. */
export async function commitContext(repo: string, message: string): Promise<void> {
  await run('git', ['add', '--', '.context'], { cwd: repo });
  const staged = await run('git', ['diff', '--cached', '--quiet', '--', '.context'], { cwd: repo });
  if (staged.code === 0) return;
  await run('git', ['-c', 'user.name=aio', '-c', 'user.email=aio@localhost', 'commit', '-m', message, '--', '.context'], {
    cwd: repo,
  });
}
